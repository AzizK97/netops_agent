from pathlib import Path

import yaml
from nornir import InitNornir

PREFIX = "clab-data_center"
TARGETS_DIR = Path("observability/prometheus/targets")
EXPORTERS = {"frr": 9342, "node": 9100}
HEADER = "# Generated by render_targets.py from inventory/.\n"


def main() -> None:
    nr = InitNornir(config_file="nornir_config.yml")
    TARGETS_DIR.mkdir(parents=True, exist_ok=True)

    for job, port in EXPORTERS.items():
        entries = [
            {
                "targets": [f"{PREFIX}-{name}:{port}"],
                "labels": {"node": name, "role": host["role"], "asn": str(host["asn"])},
            }
            for name, host in nr.inventory.hosts.items()
        ]
        path = TARGETS_DIR / f"{job}.yml"
        path.write_text(HEADER + yaml.safe_dump(entries, sort_keys=False))
        print(f"{path} written ({len(entries)} targets)")


if __name__ == "__main__":
    main()
